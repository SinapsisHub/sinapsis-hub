def clean_text_packet_content(text: str) -> str:
    """Remove stop words from text and return the cleaned string."""
    words = text.split()
    cleaned_words = [word for word in words if word.lower() not in DEFAULT_STOP_WORDS]
    cleaned_text = " ".join(cleaned_words)
    return cleaned_text


def get_docs_from_text_packets(container: DataContainer) -> list[str]:
    """Extract cleaned text content from all text packets in the container."""
    return [clean_text_packet_content(text_packet.content) for text_packet in container.texts]
